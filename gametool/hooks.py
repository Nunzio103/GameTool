"""Low-level global hooks for the keyboard and mouse (dedicated thread).

In stealth (incognito) mode no hook is installed: input is read by
polling (GetAsyncKeyState / GetCursorPos).
"""
import ctypes
import threading
import time
import traceback
from ctypes import wintypes as wt
from dataclasses import dataclass

from . import keys, winapi

_MOUSE_MSGS = {
    winapi.WM_LBUTTONDOWN: ("MouseLeft", "down"),
    winapi.WM_LBUTTONUP: ("MouseLeft", "up"),
    winapi.WM_RBUTTONDOWN: ("MouseRight", "down"),
    winapi.WM_RBUTTONUP: ("MouseRight", "up"),
    winapi.WM_MBUTTONDOWN: ("MouseMiddle", "down"),
    winapi.WM_MBUTTONUP: ("MouseMiddle", "up"),
}

# polling: mouse buttons have their own name; generic Shift/Ctrl/Alt
# (0x10-0x12) are skipped because they also arrive as the left/right key
# (as with hooks); VK_PACKET (0xE7) is the Unicode text sent by SendInput
_POLL_MOUSE = {0x01: "MouseLeft", 0x02: "MouseRight", 0x04: "MouseMiddle",
               0x05: "MouseX1", 0x06: "MouseX2"}
_POLL_SKIP = {0x10, 0x11, 0x12, 0xE7}
_POLL_VKS = tuple(vk for vk in range(1, 256) if vk not in _POLL_SKIP)
# read on every cycle together with the triggers: mouse buttons and L/R/Win modifiers
_POLL_HOT_BASE = frozenset(_POLL_MOUSE) | {0xA0, 0xA1, 0xA2, 0xA3, 0xA4, 0xA5, 0x5B, 0x5C}
POLL_INTERVAL = 0.005
# GetAsyncKeyState costs ~2 us: reading all 251 keys every 5 ms would keep
# ~10% of a core (and the GIL) busy. The full keyboard is read every
# FULL_SCAN_EVERY cycles (40 ms), except while recording/capturing a key.
FULL_SCAN_EVERY = 8


@dataclass
class InputEvent:
    kind: str           # "down", "up", "move"
    name: str           # key/button name (e.g. "A", "MouseLeft", "WheelUp")
    vk: int = 0
    injected: bool = False  # generated by software
    ours: bool = False      # generated by this app
    x: int = 0
    y: int = 0
    time: float = 0.0


class InputHook:
    """Installs the hooks and forwards events to the listeners.

    A listener is a function (InputEvent) -> bool; if it returns True the event
    is blocked (it doesn't reach other applications). If an "exclusive"
    listener is set (key capture, recording) only it receives the events.
    """

    def __init__(self):
        self.listeners = []
        self.exclusive = None
        self.want_moves = False
        # VKs of the keys held down by the user that reached the applications
        # (excluding the ones we generated and the blocked ones)
        self.user_keys = set()
        self._thread = None
        self._thread_id = None
        self._ready = threading.Event()
        # the callback references must stay alive
        self._kb_proc = winapi.HOOKPROC(self._keyboard_proc)
        self._mouse_proc = winapi.HOOKPROC(self._mouse_proc_impl)
        self._hooks = []
        self._error = None
        # mode switches and the watchdog must not overlap
        self._mode_lock = threading.RLock()
        # stealth mode (polling without hooks)
        self._stealth = False
        self._poll_thread = None
        self._poll_stop = threading.Event()
        # VKs to read on every polling cycle (the triggers): set by the engine
        self.hot_vks = lambda: ()
        # watchdog: Windows silently removes a hook that responds too slowly
        self._last_event_tick = winapi.tick_count()
        self._revive_not_before = 0.0
        self._revive_backoff = 5.0

    @property
    def stealth(self):
        return self._stealth

    def start(self, stealth=False):
        """Starts reading input; with stealth=True it never installs the hooks."""
        with self._mode_lock:
            if stealth:
                self._stealth = True
                self._start_poll()
            else:
                self._rehook()

    def stop(self):
        with self._mode_lock:
            self._stop_poll()
            self._unhook()

    # --- stealth mode (polling, no hooks) ---------------------------
    def set_stealth(self, on):
        """Turns stealth mode on/off.

        In stealth mode the low-level hooks are removed and input is read
        by polling (GetAsyncKeyState / GetCursorPos).
        Limits: the original keys can't be blocked and the mouse wheel
        can't be detected. Raises OSError if the switch fails
        (in that case the previous mode stays active).
        """
        with self._mode_lock:
            on = bool(on)
            if on == self._stealth:
                return
            if on:
                if not self._unhook():
                    raise OSError("the input hook thread did not stop")
                self._stealth = True
                self._start_poll()
            else:
                self._stop_poll()
                self._stealth = False
                try:
                    self._rehook()
                except OSError:
                    # hooks can't be installed: stay in polling instead of reading nothing at all
                    self._stealth = True
                    self._start_poll()
                    raise

    def _start_poll(self):
        # a new event for each thread: an old thread that hasn't exited yet can't
        # "wake up" again (with a single event, clear() would set it running again)
        self._poll_stop = stop = threading.Event()
        # initial state read right away, in the calling thread: a press arriving
        # while the thread starts must not be mistaken for an already pressed key
        get_state = winapi.user32.GetAsyncKeyState
        initial = {vk for vk in _POLL_VKS if get_state(vk) & 0x8000}
        self._poll_thread = threading.Thread(target=self._poll_loop, args=(stop, initial),
                                             name="StealthPoll", daemon=True)
        self._poll_thread.start()

    def _stop_poll(self):
        """Stops polling and waits for it to finish (no duplicate events when going back to hooks)."""
        if self._poll_thread:
            self._poll_stop.set()
            self._poll_thread.join(timeout=1)
            self._poll_thread = None

    # --- hooks / stealth: thread management ----------------------------------------
    def _unhook(self):
        """Removes the hooks and waits for the message loop thread to exit.

        Returns False if the thread is still alive (the hooks are still installed).
        """
        thread = self._thread
        if thread is None:
            return True
        for timeout in (2, 1):
            if self._thread_id:
                winapi.user32.PostThreadMessageW(self._thread_id, winapi.WM_QUIT, 0, 0)
            thread.join(timeout=timeout)
            if not thread.is_alive():
                break
        if thread.is_alive():
            return False
        self._thread = None
        self._thread_id = None
        return True

    def _rehook(self):
        """Restarts the thread with the low-level hooks."""
        if self._thread and self._thread.is_alive():
            return
        self._error = None
        self._thread_id = None
        self._ready = ready = threading.Event()
        self._thread = threading.Thread(target=self._loop, args=(ready,), name="InputHook", daemon=True)
        self._thread.start()
        ready.wait(5)
        if self._error is not None:
            self._thread = None
            raise self._error
        self._last_event_tick = winapi.tick_count()

    def check_alive(self, grace_ms=1000):
        """Watchdog: reinstalls the hooks if Windows removed them.

        On Windows 7 and later a low-level hook that doesn't respond in time
        (for example because the process was busy) is removed without any
        notice: macros stop working even though the app shows "on".
        If the system received input that the hooks didn't see, they are
        reinstalled. Returns True if it did so.
        """
        if self._stealth or not self._mode_lock.acquire(blocking=False):
            return False
        try:
            if self._stealth or self._thread is None:
                return False
            last_input = winapi.last_input_tick()
            # differences modulo 2^32: GetTickCount wraps to zero every 49.7 days.
            # Live hooks see every input within milliseconds, so input newer than the
            # last hook event by more than grace_ms means the hooks are gone. No need
            # to wait for a quiet moment: while gaming, input never stops.
            unseen = (last_input - self._last_event_tick) & 0xFFFFFFFF
            if unseen >= 0x80000000 or unseen < grace_ms:
                self._revive_backoff = 5.0  # the hooks see the input: all good
                return False
            if time.monotonic() < self._revive_not_before:
                return False
            # if input still doesn't arrive (e.g. a window with higher privileges)
            # don't reinstall continuously: increasing waits, up to one minute
            self._revive_not_before = time.monotonic() + self._revive_backoff
            self._revive_backoff = min(self._revive_backoff * 2, 60.0)
            if not self._unhook():
                return False
            try:
                self._rehook()
            except OSError:
                traceback.print_exc()
                return False
            return True
        finally:
            self._mode_lock.release()

    def _poll_loop(self, stop, keys_down):
        """In stealth mode, reads input at regular intervals without hooks.

        GetAsyncKeyState and GetCursorPos are ordinary API calls and don't
        install any hook in the system. In exchange the original key can't
        be blocked. State changes caused by our macros are recognized with
        winapi.sent_by_us and marked as `ours`.
        """
        get_state = winapi.user32.GetAsyncKeyState
        hot = _POLL_HOT_BASE
        last_pos = None
        tick = 0
        while not stop.is_set():
            if self.exclusive is not None or tick % FULL_SCAN_EVERY == 0:
                scan = _POLL_VKS
                try:
                    hot = _POLL_HOT_BASE.union(self.hot_vks())
                except Exception:
                    traceback.print_exc()
            else:
                # keys already pressed are always read, to see their release right away
                scan = hot | keys_down
            tick += 1
            now_down = {vk for vk in scan if get_state(vk) & 0x8000}
            if now_down != keys_down:
                for vk in now_down - keys_down:
                    self._stealth_event("down", vk)
                for vk in keys_down - now_down:
                    self._stealth_event("up", vk)
                keys_down = now_down
            # --- position (for listeners that use want_moves) ---
            if self.want_moves:
                pos = winapi.stealth_mouse_pos()
                if pos != last_pos:
                    last_pos = pos
                    self._dispatch(InputEvent(kind="move", name="Move", x=pos[0], y=pos[1],
                                              time=time.perf_counter()))
            stop.wait(POLL_INTERVAL)

    def _stealth_event(self, kind, vk):
        down = kind == "down"
        ours = winapi.sent_by_us(vk, down)
        mouse = _POLL_MOUSE.get(vk)
        ev = InputEvent(kind=kind, name=mouse or keys.name_from_vk(vk),
                        vk=0 if mouse else vk, ours=ours, injected=ours,
                        time=time.perf_counter())
        if mouse:
            ev.x, ev.y = winapi.stealth_mouse_pos()
        elif not ours:  # as with hooks: only keys really pressed by the user
            if down:
                self.user_keys.add(vk)
            else:
                self.user_keys.discard(vk)
        self._dispatch(ev)

    def _loop(self, ready):
        self._thread_id = winapi.kernel32.GetCurrentThreadId()
        hmod = winapi.kernel32.GetModuleHandleW(None)
        hooks = []
        for kind, proc in ((winapi.WH_KEYBOARD_LL, self._kb_proc), (winapi.WH_MOUSE_LL, self._mouse_proc)):
            hook = winapi.user32.SetWindowsHookExW(kind, proc, hmod, 0)
            if not hook:
                self._error = ctypes.WinError(ctypes.get_last_error())
                break
            hooks.append(hook)
        else:
            self._hooks = hooks
            ready.set()
            msg = wt.MSG()
            while winapi.user32.GetMessageW(ctypes.byref(msg), None, 0, 0) > 0:
                winapi.user32.TranslateMessage(ctypes.byref(msg))
                winapi.user32.DispatchMessageW(ctypes.byref(msg))
        for hook in hooks:
            winapi.user32.UnhookWindowsHookEx(hook)
        if self._hooks is hooks:
            self._hooks = []
        ready.set()

    def _dispatch(self, event):
        try:
            if self.exclusive is not None:
                return bool(self.exclusive(event))
            block = False
            for listener in list(self.listeners):
                if listener(event):
                    block = True
            return block
        except Exception:
            traceback.print_exc()
            return False

    def _keyboard_proc(self, n_code, w_param, l_param):
        self._last_event_tick = winapi.tick_count()
        if n_code == 0:
            data = winapi.KBDLLHOOKSTRUCT.from_address(l_param)
            if w_param in (winapi.WM_KEYDOWN, winapi.WM_SYSKEYDOWN):
                kind = "down"
            elif w_param in (winapi.WM_KEYUP, winapi.WM_SYSKEYUP):
                kind = "up"
            else:
                kind = None
            if kind:
                event = InputEvent(
                    kind=kind,
                    name=keys.name_from_vk(data.vkCode),
                    vk=data.vkCode,
                    injected=bool(data.flags & winapi.LLKHF_INJECTED),
                    ours=data.dwExtraInfo == winapi.MAGIC,
                    time=time.perf_counter(),
                )
                blocked = self._dispatch(event)
                if not event.ours:
                    if kind == "up":
                        self.user_keys.discard(data.vkCode)
                    elif not blocked:
                        self.user_keys.add(data.vkCode)
                if blocked:
                    return 1
        return winapi.user32.CallNextHookEx(None, n_code, w_param, l_param)

    def _mouse_proc_impl(self, n_code, w_param, l_param):
        self._last_event_tick = winapi.tick_count()
        if n_code == 0:
            data = winapi.MSLLHOOKSTRUCT.from_address(l_param)
            event = None
            if w_param in _MOUSE_MSGS:
                name, kind = _MOUSE_MSGS[w_param]
                event = InputEvent(kind=kind, name=name)
            elif w_param in (winapi.WM_XBUTTONDOWN, winapi.WM_XBUTTONUP):
                button = (data.mouseData >> 16) & 0xFFFF
                name = "MouseX1" if button == 1 else "MouseX2"
                event = InputEvent(kind="down" if w_param == winapi.WM_XBUTTONDOWN else "up", name=name)
            elif w_param == winapi.WM_MOUSEWHEEL:
                delta = ctypes.c_short((data.mouseData >> 16) & 0xFFFF).value
                event = InputEvent(kind="down", name="WheelUp" if delta > 0 else "WheelDown")
            elif w_param == winapi.WM_MOUSEMOVE and self.want_moves:
                event = InputEvent(kind="move", name="Move")
            if event is not None:
                event.injected = bool(data.flags & winapi.LLMHF_INJECTED)
                event.ours = data.dwExtraInfo == winapi.MAGIC
                event.x, event.y = data.pt.x, data.pt.y
                event.time = time.perf_counter()
                if self._dispatch(event):
                    return 1
        return winapi.user32.CallNextHookEx(None, n_code, w_param, l_param)
